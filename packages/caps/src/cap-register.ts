import { BREACH_CAP_CATEGORY, type CapDescriptor } from "./sdk";

type RegisterCap = Pick<
  CapDescriptor,
  "id" | "title" | "provider" | "credentials"
>;

const INTRO = `# Cap register

**What this is:** every Cap, who it gets its data from, where that provider's terms live, and what they say about commercial use. One table per category.\u0020\u0020
**What this is not:** legal advice. Each verdict is read from the provider's own published page, linked in the **Terms** column. Where the terms were silent or could not be read, the value is \`unknown\`, never a guess: check the linked page before you rely on a Cap commercially.

Generated by \`pnpm generate:caps\` from the \`provider\` block of each Cap (\`packages/caps/src/providers/\`). Do not edit by hand: a stale file fails \`packages/caps/src/__tests__/cap-register.test.ts\` and the CI job "CapDescriptor drift".

## How to read it

- **Tier** is what the plan the Cap needs costs: \`free\`, \`freemium\` (free tier plus paid tiers), \`paid\`, or \`self\` (no third party).
- **Commercial use** is for that plan: \`allowed\` (the provider's text says so), \`restricted\` (a paid plan, a licence or conditions are needed), \`forbidden\` (the terms prohibit it) or \`unknown\`.
- **Attribution** is the credit the provider's terms ask for. The web app shows it beside the Cap's Job output.
- **Breach** Caps (the \`breach\` category, flag \`breach\` in the descriptor) are off until an operator sets \`WD_ENABLE_BREACH_CAPS=1\`: see the note above that table.
- **Credentials** are the vault slots the Cap reads (\`?\` marks an optional one); set them in Settings.
`;

const BREACH_NOTE =
  "These Caps query breach and leak corpora about people. They are **opt-in**: while `WD_ENABLE_BREACH_CAPS` is off (the default) none of them can be queued or run, and the web app shows them disabled. Enabling them makes the operator responsible for a lawful basis and for each provider's terms. See [`caps-lexicon`](caps-lexicon.md#breach-caps-are-opt-in).";

/** Escape what would break a Markdown table cell or a link label: pipes and brackets. */
const cell = (text: string) =>
  text.replaceAll("|", "\\|").replaceAll("[", "\\[").replaceAll("]", "\\]");

const link = (label: string, url: string) => `[${cell(label)}](${url})`;

function credentialCell(credentials: RegisterCap["credentials"]): string {
  if (!credentials?.length) return "none";
  return credentials
    .map((spec) => {
      if ("anyOf" in spec)
        return spec.anyOf.map((n) => `\`${n}\``).join(" or ");
      return `\`${spec.name}\`${spec.optional === true ? "?" : ""}`;
    })
    .join(", ");
}

/** The generated `docs/reference/platform/cap-register.md`, from the descriptors. */
export function renderCapRegister(caps: readonly RegisterCap[]): string {
  const byCategory = new Map<string, RegisterCap[]>();
  for (const cap of caps) {
    const category = cap.id.split(".")[0] ?? cap.id;
    byCategory.set(category, [...(byCategory.get(category) ?? []), cap]);
  }
  const sections = [...byCategory.keys()].sort().map((category) => {
    const rows = [...(byCategory.get(category) ?? [])]
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((cap) => {
        const { provider } = cap;
        const attribution = provider.attribution
          ? link(provider.attribution.text, provider.attribution.url)
          : "none";
        return `| \`${cap.id}\` | ${link(provider.name, provider.url)} | ${link("terms", provider.termsUrl)} | ${provider.tier} | ${provider.commercialUse} | ${attribution} | ${credentialCell(cap.credentials)} |`;
      });
    const note = category === BREACH_CAP_CATEGORY ? [BREACH_NOTE, ""] : [];
    return [
      `## ${category}`,
      "",
      ...note,
      "| Cap | Provider | Terms | Tier | Commercial use | Attribution | Credentials |",
      "| --- | --- | --- | --- | --- | --- | --- |",
      ...rows,
    ].join("\n");
  });
  return `${INTRO}\n${sections.join("\n\n")}\n`;
}

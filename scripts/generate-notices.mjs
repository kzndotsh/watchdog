#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md from the production dependency licenses.
 * `--check` fails when the committed file differs from what would be written.
 * Prebuilt per-platform native packages are left out so the file is identical
 * on every machine; `check-licenses.mjs` still checks whatever is installed.
 *
 *   node scripts/generate-notices.mjs [--check] [--input <pnpm-licenses.json>]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import {
  asRecord,
  isPlatformBinary,
  loadProdLicenses,
} from "./lib/prod-licenses.mjs";

const FILE = path.resolve(import.meta.dirname, "..", "THIRD_PARTY_NOTICES.md");

const EXCEPTIONS = path.resolve(import.meta.dirname, "license-exceptions.json");
const exceptions = asRecord(
  existsSync(EXCEPTIONS) ? JSON.parse(readFileSync(EXCEPTIONS, "utf-8")) : {}
);

// A reviewed exception replaces the reported license while pnpm still reports the same one.
const rows = loadProdLicenses(process.argv.slice(2))
  .filter((row) => !isPlatformBinary(row.name))
  .map((row) => {
    const reviewed = asRecord(exceptions[row.name]);
    return reviewed.reported === row.license &&
      typeof reviewed.license === "string"
      ? { ...row, license: reviewed.license }
      : row;
  });
/** @type {Map<string, typeof rows>} */
const groups = new Map();
for (const row of rows) {
  groups.set(row.license, [...(groups.get(row.license) ?? []), row]);
}

const out = [
  "# Third-party notices",
  "",
  "Watchdog is licensed under AGPL-3.0-only (see [LICENSE](LICENSE)). Its production dependencies keep their own licenses, listed here by license. Generated by `pnpm generate:notices` from `pnpm licenses list --prod`; do not edit by hand (`pnpm check:notices` fails when it is stale).",
  "",
  "Prebuilt per-platform native binaries (esbuild, sharp and its libvips, rollup, lightningcss and similar) are omitted because the set depends on the machine. Their licenses are checked by `pnpm check:licenses`. `@img/sharp-libvips-*` is LGPL-3.0-or-later.",
  "",
  `${rows.length} packages.`,
  "",
];
for (const license of [...groups.keys()].sort((a, b) => a.localeCompare(b))) {
  const pkgs = groups.get(license) ?? [];
  out.push(`## ${license} (${pkgs.length})`, "");
  for (const pkg of pkgs) {
    out.push(
      `- ${pkg.name} ${pkg.version}${pkg.homepage ? ` (<${pkg.homepage}>)` : ""}`
    );
  }
  out.push("");
}
const text = `${out.join("\n").trimEnd()}\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(FILE) ? readFileSync(FILE, "utf-8") : "";
  if (current !== text) {
    console.error(
      "generate:notices: THIRD_PARTY_NOTICES.md is out of date. Run pnpm generate:notices and commit it."
    );
    process.exit(1);
  }
  console.log("generate:notices: ok");
} else {
  writeFileSync(FILE, text);
  console.log(`generate:notices: wrote ${rows.length} packages`);
}

#!/usr/bin/env node
/**
 * Writes `env.example` and `docs/reference/platform/configuration.md` from the env metadata in
 * `packages/env/src` (the Zod fields' `.meta()` plus `reference.ts`). `--check` writes nothing and
 * exits 1 when either file differs from what would be written, and when `env.production.example`
 * (hand-maintained: it is a compose file's environment, not the app's) lists a variable the
 * metadata does not know or omits one the app validates.
 *
 *   node scripts/generate-env-docs.mjs [--check] [--source <packages/env/src>]
 *
 * `--source` points at the env package source (default: next to this script's repo root); the
 * gate test uses it to run against a fixture repo while the schema's dependencies resolve from
 * the real install.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const sourceFlag = args.indexOf("--source");
const source = path.resolve(
  sourceFlag === -1 ? path.join(root, "packages/env/src") : args[sourceFlag + 1]
);

/** @typedef {import("../packages/env/src/describe").EnvRow} EnvRow */

const { tsImport } = await import("tsx/esm/api");
// oxlint-disable-next-line typescript/no-unsafe-assignment -- tsImport is typed `any`; the module is packages/env/src/describe.ts
const described = await tsImport(
  path.join(source, "describe.ts"),
  import.meta.url
);
/** @param {{ envRows: () => EnvRow[] }} envModule */
const rowsOf = (envModule) => envModule.envRows();
// oxlint-disable-next-line typescript/no-unsafe-argument -- the module is packages/env/src/describe.ts
const rows = rowsOf(described);

const ENV_EXAMPLE = path.join(root, "env.example");
const REFERENCE = path.join(root, "docs/reference/platform/configuration.md");
const PRODUCTION_EXAMPLE = path.join(root, "env.production.example");

/** Group titles in first-seen order. */
const groups = [...new Set(rows.map((row) => row.group))];

/**
 * @param {string} text
 * @param {string} prefix
 * @param {number} width
 */
function wrap(text, prefix, width = 88) {
  const lines = [];
  let line = prefix;
  for (const word of text.split(" ")) {
    if (line.length + word.length + 1 > width && line !== prefix) {
      lines.push(line);
      line = prefix;
    }
    line += (line === prefix ? "" : " ") + word;
  }
  lines.push(line);
  return lines;
}

/** @param {EnvRow} row */
function notes(row) {
  const secret = row.sensitive ? ", secret" : "";
  const fallback = row.default === undefined ? "" : `, default ${row.default}`;
  return `${row.required ? "Required" : "Optional"}${secret}${fallback}.`;
}

function envExample() {
  const out = [
    "# ============================================================",
    "# Watchdog platform: environment variables (development)",
    "# GENERATED by `pnpm generate:env` from packages/env/src. Do not edit:",
    "# change the field's .meta() and regenerate (`pnpm check:env` fails when stale).",
    "# `just env` copies this to .env and fills the secrets; Cap API keys live in the",
    "# Settings vault, not here. Every variable, with defaults and which service reads it:",
    "# docs/reference/platform/configuration.md. Production: env.production.example.",
    "# ============================================================",
  ];
  for (const group of groups) {
    const members = rows.filter((row) => row.group === group && row.inExample);
    if (members.length === 0) continue;
    out.push("", `# ---- ${group} ----`);
    for (const row of members) {
      out.push(...wrap(row.description, "# "), `# ${notes(row)}`);
      const active =
        row.source === "schema"
          ? row.required || (row.example !== undefined && !row.sensitive)
          : row.example !== undefined;
      const value = row.sensitive ? "" : (row.example ?? "");
      out.push(`${active ? "" : "# "}${row.name}=${value}`);
    }
  }
  return `${out.join("\n")}\n`;
}

/** @param {string} value */
const cell = (value) => value.replaceAll("|", "\\|");

/** @param {EnvRow} row */
const entrypoints = (row) =>
  row.usedBy.length === 0 ? "compose" : row.usedBy.join(", ");

function reference() {
  const out = [
    "# Configuration reference",
    "",
    "**What this is:** every environment variable Watchdog reads: what it does, its default, whether it is required, whether it is a secret and which entrypoint reads it.  ",
    "**What this is not:** a setup walkthrough ([`self-host`](../../how-to/self-host.md), [`local-dev`](../../how-to/local-dev.md)) or the Cap API keys, which live in the Settings vault.",
    "",
    "Generated by `pnpm generate:env` from the env metadata in `packages/env/src` (each field's `.meta()` and `reference.ts`). Do not edit by hand: `pnpm check:env` fails when this file or `env.example` is stale. `env.production.example` is hand-maintained (it is the compose file's environment), and the same check fails when it lists a variable that is not below or omits one the app validates.",
    "",
    "## How to read it",
    "",
    "- **Required** means startup fails without it. `web` and `worker` validate the same schema, so both containers need every required variable, even one only the web app uses.",
    "- **Secret** variables are written blank in `env.example` and must never be logged or committed.",
    "- **Used by** names the entrypoint that reads the variable: `web` (the app and API), `worker`, `cli` (`wd`), `migrate` (the container's migrator), `site` (the marketing site) or `compose` (only `docker-compose.prod.yml` reads it).",
    "- **Placeholders and short secrets are refused at startup.** `BETTER_AUTH_SECRET` and `WD_MASTER_VAULT_KEY` need at least 32 characters and may not be a known placeholder (`change-me...`, `secret`, `password`, ...); `S3_SECRET_KEY` may not be a placeholder, nor the development default when `NODE_ENV` is `production`. The error names the variable. Generate a value with `openssl rand -base64 32`.",
    "- An empty value counts as unset.",
  ];
  for (const group of groups) {
    out.push(
      "",
      `## ${group}`,
      "",
      "| Variable | Description | Default | Required | Secret | Used by |",
      "| --- | --- | --- | --- | --- | --- |"
    );
    for (const row of rows.filter((candidate) => candidate.group === group)) {
      out.push(
        `| \`${row.name}\` | ${cell(row.description)} | ${
          row.default === undefined ? "none" : `\`${cell(row.default)}\``
        } | ${row.required ? "yes" : "no"} | ${row.sensitive ? "yes" : "no"} | ${entrypoints(row)} |`
      );
    }
  }
  return `${out.join("\n")}\n`;
}

/**
 * Names `env.production.example` sets or documents: `KEY=` and `# KEY=` lines.
 * @param {string} text
 */
function productionKeys(text) {
  /** @type {Set<string>} */
  const keys = new Set();
  for (const line of text.split("\n")) {
    const match = /^#? ?([A-Z][A-Z0-9_]+)=/.exec(line);
    if (match) keys.add(match[1]);
  }
  return keys;
}

/** @type {string[]} */
const problems = [];

/**
 * @param {string} file
 * @param {string} content
 */
function sync(file, content) {
  const label = path.relative(root, file);
  if (check) {
    const current = existsSync(file) ? readFileSync(file, "utf-8") : null;
    if (current !== content) {
      problems.push(
        `${label} is stale: run \`pnpm generate:env\` and commit it`
      );
    }
    return;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  process.stdout.write(`generate:env: wrote ${label}\n`);
}

sync(ENV_EXAMPLE, envExample());
sync(REFERENCE, reference());

if (check && existsSync(PRODUCTION_EXAMPLE)) {
  const keys = productionKeys(readFileSync(PRODUCTION_EXAMPLE, "utf-8"));
  const known = new Set(rows.map((row) => row.name));
  // The compose-only variables are optional there; the app's own fields are all listed.
  for (const row of rows) {
    if (row.source === "schema" && !keys.has(row.name)) {
      problems.push(
        `env.production.example does not list ${row.name} (add \`${row.name}=\` or \`# ${row.name}=\`)`
      );
    }
  }
  for (const key of keys) {
    if (!known.has(key)) {
      problems.push(
        `env.production.example lists ${key}, which no env metadata describes (add it to packages/env/src/reference.ts or remove it)`
      );
    }
  }
}

if (problems.length > 0) {
  for (const problem of problems)
    process.stderr.write(`check:env: ${problem}\n`);
  process.exit(1);
}
if (check) process.stdout.write("check:env: ok\n");
